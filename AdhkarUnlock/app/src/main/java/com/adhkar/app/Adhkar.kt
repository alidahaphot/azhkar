    // Any other hour shows evening adhkar. Change these two numbers to adjust the windows.
    const val MORNING_START = 4
    const val EVENING_START = 15

    fun isMorning(hour: Int): Boolean = hour >= MORNING_START && hour < EVENING_START

    fun isMorningNow(): Boolean = isMorning(Calendar.getInstance().get(Calendar.HOUR_OF_DAY))

    // Returns the next dhikr (cycling through the list) and whether it is a morning one.
    fun next(context: Context): Pair<Dhikr, Boolean> {
        val morning = isMorningNow()
        val list = if (morning) MORNING else EVENING
        val key = if (morning) "idx_morning" else "idx_evening"
        val i = Prefs.nextIndex(context, key, list.size)
        return Pair(list[i], morning)
    }

